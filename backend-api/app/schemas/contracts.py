class EndpointEvent(BaseModel):
    """Normalized telemetry event emitted by endpoint sensor components."""

    model_config = ConfigDict(extra="forbid")

    event_id: UUID = Field(
        ...,
        description="Unique identifier for the endpoint event.",
    )
    event_type: EndpointEventType = Field(
        ...,
        description="Category of telemetry event observed.",
    )
    timestamp: datetime = Field(
        ...,
        description="Timezone-aware timestamp (ISO 8601 UTC) when the event occurred.",
    )
    source_component: str = Field(
        ...,
        min_length=1,
        description="Identifier of the monitor or sensor component emitting the event.",
    )
    file_path: Optional[str] = Field(
        default=None,
        description="Path of the affected filesystem object, if applicable.",
    )
    file_hash: Optional[str] = Field(
        default=None,
        pattern=r"^[a-fA-F0-9]{64}$",
        description="SHA-256 hexadecimal hash digest of the associated file, if available.",
    )
    process_id: Optional[int] = Field(
        default=None,
        ge=0,
        description="Process ID (PID) associated with the event.",
    )
    parent_process_id: Optional[int] = Field(
        default=None,
        ge=0,
        description="Parent Process ID (PPID) associated with the event.",
    )
    metadata: Dict[str, Any] = Field(
        default_factory=dict,
        description="Arbitrary supplementary event metadata.",
    )

    @field_validator("timestamp")
    @classmethod
    def validate_timezone_aware(cls, v: datetime) -> datetime:
        """Ensure the timestamp includes explicit timezone information."""
        if v.tzinfo is None:
            raise ValueError("Timestamp must be timezone-aware (e.g. UTC).")
        return v


class DetectionEvidence(BaseModel):
    """Structured detection indicator generated by analysis modules."""

    model_config = ConfigDict(extra="forbid")

    evidence_id: UUID = Field(
        ...,
        description="Unique identifier for this specific piece of evidence.",
    )
    incident_id: UUID = Field(
        ...,
        description="Associated security incident identifier.",
    )
    source: str = Field(
        ...,
        min_length=1,
        description="Detection subsystem name (e.g., yara, ml_pe, canary_monitor).",
    )
    indicator: str = Field(
        ...,
        min_length=1,
        description="Specific indicator, rule name, or pattern detected.",
    )
    severity: DetectionSeverity = Field(
        ...,
        description="Severity classification for the detected indicator.",
    )
    description: str = Field(
        ...,
        min_length=1,
        description="Human-readable explanation of why the indicator triggered.",
    )
    observed_value: Optional[str] = Field(
        default=None,
        description="Matching artifact or specific string observed.",
    )
    confidence: Optional[float] = Field(
        default=None,
        ge=0.0,
        le=1.0,
        description="Detection certainty from 0.0 to 1.0.",
    )
    score_contribution: Optional[float] = Field(
        default=None,
        description="Calculated point contribution toward the composite score.",
    )
    details: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Supplemental structured technical metadata.",
    )
    observed_at: datetime = Field(
        ...,
        description="Timezone-aware timestamp when the indicator was evaluated.",
    )
    analysis_job_id: Optional[UUID] = Field(
        default=None,
        description="Optional ID of the analysis job that produced the evidence.",
    )

    @field_validator("observed_at")
    @classmethod
    def validate_timezone_aware(cls, v: datetime) -> datetime:
        """Ensure the timestamp includes explicit timezone information."""
        if v.tzinfo is None:
            raise ValueError("Timestamp must be timezone-aware (e.g. UTC).")
        return v


class HashReputationSummary(BaseModel):
    """Structured local hash-reputation outcome for an evaluated file hash."""

    model_config = ConfigDict(extra="forbid")

    file_hash: str = Field(
        ...,
        pattern=r"^[a-f0-9]{64}$",
        description="Canonical 64-character lowercase SHA-256 hash digest.",
    )
    is_known: bool = Field(
        ...,
        description="Whether the hash was found in the reputation database.",
    )
    verdict: Optional[SecurityVerdict] = Field(
        default=None,
        description="Reputation verdict configured for this hash, or None if unknown.",
    )
    list_type: Optional[HashListType] = Field(
        default=None,
        description="Reputation list classification, or None if unknown.",
    )


