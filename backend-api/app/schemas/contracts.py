"""Shared data contracts and Pydantic validation models for Sentinel-EDR.

These models define the public data transfer contracts across backend modules
and adhere to the language-neutral JSON Schemas in `shared/schemas/`.
"""

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field, field_validator


# ==============================================================================
# Common Enums
# ==============================================================================

class SecurityVerdict(str, Enum):
    """Normalized security verdict for evaluated objects or incidents."""
    BENIGN = "BENIGN"
    SUSPICIOUS = "SUSPICIOUS"
    MALICIOUS = "MALICIOUS"


class HashListType(str, Enum):
    """Classification of hash reputation lists."""
    ALLOWLIST = "ALLOWLIST"
    BLOCKLIST = "BLOCKLIST"
    CUSTOM = "CUSTOM"


class AnalysisJobStatus(str, Enum):
    """Lifecycle states of an analysis pipeline job."""
    QUEUED = "QUEUED"
    IN_PROGRESS = "IN_PROGRESS"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"
    CANCELLED = "CANCELLED"


class IncidentStatus(str, Enum):
    """Investigation and handling lifecycle states for security incidents."""
    OPEN = "OPEN"
    INVESTIGATING = "INVESTIGATING"
    CONTAINED = "CONTAINED"
    RESOLVED = "RESOLVED"
    CLOSED = "CLOSED"


class ResponseActionStatus(str, Enum):
    """Execution status for active mitigation and response operations."""
    PENDING = "PENDING"
    IN_PROGRESS = "IN_PROGRESS"
    SUCCEEDED = "SUCCEEDED"
    FAILED = "FAILED"
    CANCELLED = "CANCELLED"


class DetectionSeverity(str, Enum):
    """Severity ratings for detection indicators and security alerts."""
    INFO = "INFO"
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class ComponentAvailability(str, Enum):
    """Operational health status of individual detection and system modules."""
    AVAILABLE = "available"
    UNAVAILABLE = "unavailable"
    DEGRADED = "degraded"
    DISABLED = "disabled"
    NOT_INITIALIZED = "not_initialized"
    UNKNOWN = "unknown"


class EndpointEventType(str, Enum):
    """Types of raw telemetry and activity events observed on endpoints."""
    FILE_CREATED = "file_created"
    FILE_MODIFIED = "file_modified"
    FILE_RENAMED = "file_renamed"
    FILE_DELETED = "file_deleted"
    PROCESS_OBSERVED = "process_observed"
    CANARY_TRIGGERED = "canary_triggered"


